// Run from the repository: node lib/games/bartender/scene3d/build_scene.cjs
// Keep the scene inside this feature. Flutter needs no new asset declaration,
// CDN, dependency or local server. esbuild/three are already in the repository.
const { buildSync } = require('esbuild');
const { writeFileSync } = require('node:fs');
const { join } = require('node:path');
const result = buildSync({
  entryPoints: [join(__dirname, 'scene.mjs')], bundle: true, minify: true,
  format: 'iife', target: 'es2020', write: false, legalComments: 'eof',
});
const script = result.outputFiles[0].text;
if (script.includes("'''")) throw new Error('Unsafe Dart raw string delimiter');
writeFileSync(join(__dirname, 'scene_bundle.dart'),
  '// GENERATED by scene3d/build_scene.cjs; edit scene.mjs instead.\n' +
  '// Includes Three.js under its MIT license (license text in bundle).\n' +
  "const bartenderSceneScript = r'''" + script + "''';\n", 'utf8');
console.log(`Offline scene bundled: ${script.length} bytes`);
